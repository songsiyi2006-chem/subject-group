@dataclass(frozen=True)
class Config:
    e_total_nm: float = 100.0
    t_total_nm: float = 100.0
    kd_e_nm: float = 10.0
    kd_t_nm: float = 100.0
    vmax_nm_h: float = 12.0
    km_nm: float = 10.0
    hours: float = 24.0
    basal_turnover_h: float = 0.0
    points: int = 181
    heatmap_points: int = 41
    conformers: int = 100
    seed: int = 20260910
    compatible_low_a: float = 8.0
    compatible_high_a: float = 12.0

    def validate(self):
        for name in ("e_total_nm", "t_total_nm", "kd_e_nm", "kd_t_nm", "vmax_nm_h", "km_nm", "hours"):
            value = getattr(self, name)
            if not np.isfinite(value) or value <= 0:
                raise ValueError(f"{name} must be finite and positive")
        if not np.isfinite(self.basal_turnover_h) or self.basal_turnover_h < 0:
            raise ValueError("basal_turnover_h must be finite and nonnegative")
        if self.points < 81 or self.heatmap_points < 5 or self.conformers < 100:
            raise ValueError("Use at least 81 dose points, 5 heatmap points and 100 conformers")
        if not (0 <= self.seed < 2**31 - 1):
            raise ValueError("seed must be in [0, 2**31-1)")
        if not (0 < self.compatible_low_a < self.compatible_high_a):
            raise ValueError("Invalid illustrative compatibility window")


class Equilibrium:
    """Positive log-concentration 3D root solver with independent scalar backup.

    Species order: P, E, T, EP, PT, EPT. A successful optimizer status alone
    is never accepted: log mass balance and physical bounds must also pass.
    """
    def __init__(self):
        self.counts = {"hybr": 0, "lm": 0, "scalar_fallback": 0}
        self.max_relative_balance_error = 0.0

    @staticmethod
    def validate_inputs(p0, e0, t0, ke, kt, alpha):
        values = np.array([p0, e0, t0, ke, kt, alpha], float)
        if not np.all(np.isfinite(values)) or min(p0, e0, t0) < 0 or min(ke, kt, alpha) <= 0:
            raise ValueError("Totals must be nonnegative; Kd and alpha must be positive and finite")

    @staticmethod
    def fixed_free(p, e0, t0, ke, kt, alpha):
        """Stable quadratic solution at fixed free P; supports NumPy arrays."""
        p = np.maximum(np.asarray(p, float), np.finfo(float).tiny)
        q = (ke + p) * (kt + p) / (alpha * p)
        # Scale before squaring: zero-dose vector lanes use tiny positive p,
        # so q can be huge even though the physical ternary concentration is 0.
        scale = np.maximum(q, np.maximum(e0, t0))
        en, tn, qn = e0/scale, t0/scale, q/scale
        disc = np.sqrt((en-tn)**2 + 2*qn*(en+tn) + qn*qn)
        c = (2*en*t0) / (en+tn+qn+disc)
        e = (e0 - c) / (1 + p / ke)
        t = (t0 - c) / (1 + p / kt)
        ep, pt = e * p / ke, t * p / kt
        return p, e, t, ep, pt, c

    @classmethod
    def scalar(cls, p0, e0, t0, ke, kt, alpha):
        """Independent 1D Brent solution used for validation and fallback."""
        cls.validate_inputs(p0, e0, t0, ke, kt, alpha)
        if p0 == 0:
            return np.array([0., e0, t0, 0., 0., 0.])
        lower = p0 / (1 + e0/ke + t0/kt + alpha*e0*t0/(ke*kt))
        def residual(lp):
            z = cls.fixed_free(np.exp(lp), e0, t0, ke, kt, alpha)
            return np.log((z[0]+z[3]+z[4]+z[5])/p0)
        lo, hi = np.log(lower) - 1e-8, np.log(p0) + 1e-8
        lp = brentq(residual, lo, hi, xtol=1e-12, rtol=1e-14)
        return np.asarray(cls.fixed_free(np.exp(lp), e0, t0, ke, kt, alpha), float)

    @classmethod
    def batch(cls, p0, e0, t0, ke, kt, alpha):
        """Vectorized log-space bisection of the same exact mass balances.

        Avoids thousands of 3D solves inside a time integrator. A tight
        fixed bisection count is independently cross-checked in validation.
        """
        p0, e0, t0, alpha = np.broadcast_arrays(p0, e0, t0, alpha)
        safe = np.maximum(p0, 1e-300)
        lo = np.log(safe / (1 + e0/ke + t0/kt + alpha*e0*t0/(ke*kt))) - 1e-8
        hi = np.log(safe) + 1e-8
        for _ in range(55):
            mid = (lo+hi)/2
            z = cls.fixed_free(np.exp(mid), e0, t0, ke, kt, alpha)
            above = z[0]+z[3]+z[4]+z[5] > p0
            hi = np.where(above, mid, hi)
            lo = np.where(above, lo, mid)
        c = cls.fixed_free(np.exp((lo+hi)/2), e0, t0, ke, kt, alpha)[5]
        return np.where(p0 > 0, c, 0.)

    def solve(self, p0, e0, t0, ke, kt, alpha):
        self.validate_inputs(p0, e0, t0, ke, kt, alpha)
        if min(p0, e0, t0) == 0:
            return self.scalar(p0, e0, t0, ke, kt, alpha)
        logtot = np.log([p0, e0, t0])
        lke, lkt, la = np.log([ke, kt, alpha])
        def logs(x):
            p, e, t = x
            return np.array([p, e, t, e+p-lke, t+p-lkt, la+e+p+t-lke-lkt])
        def fun(x):
            z = logs(x)
            return np.array([logsumexp(z[[0,3,4,5]]), logsumexp(z[[1,3,5]]), logsumexp(z[[2,4,5]])]) - logtot
        # Uncooperative binary estimates are only a starting point, never a result.
        pguess = p0 / (1+e0/ke+t0/kt)
        x0 = np.log([pguess, e0/(1+pguess/ke), t0/(1+pguess/kt)])
        accepted = None
        for method in ("hybr", "lm"):
            options = {"xtol": 1e-10, "maxfev": 1000} if method == "hybr" else {"ftol": 1e-12, "xtol": 1e-12, "maxiter": 2000}
            ans = root(fun, x0, method=method, options=options)
            if np.all(np.isfinite(ans.x)) and np.max(np.abs(fun(ans.x))) < 2e-9:
                candidate = np.exp(logs(ans.x))
                if candidate[5] <= min(p0,e0,t0)*(1+1e-8):
                    accepted = candidate
                    self.counts[method] += 1
                    break
        if accepted is None:
            accepted = self.scalar(p0,e0,t0,ke,kt,alpha)
            self.counts["scalar_fallback"] += 1
        z = accepted
        sums = np.array([z[0]+z[3]+z[4]+z[5], z[1]+z[3]+z[5], z[2]+z[4]+z[5]])
        error = float(np.max(np.abs(sums/np.array([p0,e0,t0])-1)))
        self.max_relative_balance_error = max(self.max_relative_balance_error, error)
        if error > 1e-8 or not np.all(np.isfinite(z)) or np.min(z) < 0:
            raise ArithmeticError(f"Equilibrium validation failed: {error=}")
        return z


def write_csv(path, rows):
    rows = list(rows)
    if not rows:
        raise ValueError(f"Refusing to write empty table: {path}")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def dump_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False)+"\n", encoding="utf-8")


def exact_optimum(e0, t0, ke, kt, alpha):
    pf = math.sqrt(ke*kt)
    z = np.asarray(Equilibrium.fixed_free(pf,e0,t0,ke,kt,alpha),float)
    return float(z[0]+z[3]+z[4]+z[5]), float(z[5])


def threshold_window(fn, peak_log, peak_y, fraction, bounds=(-3.,6.)):
    def g(x):
        return fn(x) - fraction*peak_y
    # None means the edge was not bracketed in the requested concentration range.
    lower = 10**brentq(g,bounds[0],peak_log) if g(bounds[0]) < 0 else None
    upper = 10**brentq(g,peak_log,bounds[1]) if g(bounds[1]) < 0 else None
    return lower, upper


def equilibrium_profiles(cfg, engine, out):
    doses = np.logspace(-3,6,cfg.points)  # nM = 1e-12 to 1e-3 M
    data, metrics, rows = {}, [], []
    for alpha in ALPHAS:
        species = np.array([engine.solve(p,cfg.e_total_nm,cfg.t_total_nm,cfg.kd_e_nm,cfg.kd_t_nm,alpha) for p in doses])
        data[alpha] = species
        def fn(x):
            return engine.scalar(10**x,cfg.e_total_nm,cfg.t_total_nm,cfg.kd_e_nm,cfg.kd_t_nm,alpha)[5]
        opt = minimize_scalar(lambda x:-fn(x),bounds=(-3,6),method="bounded",options={"xatol":1e-10})
        if not opt.success:
            raise ArithmeticError("Peak optimizer failed")
        exact_p, exact_c = exact_optimum(cfg.e_total_nm,cfg.t_total_nm,cfg.kd_e_nm,cfg.kd_t_nm,alpha)
        lo, hi = threshold_window(fn,opt.x,-opt.fun,.8)
        metrics.append(dict(alpha=alpha,peak_total_p_nm=float(10**opt.x),peak_ept_nm=float(-opt.fun),
                            exact_peak_total_p_nm=exact_p,exact_peak_ept_nm=exact_c,
                            supplied_formula_p_nm=math.sqrt((cfg.kd_e_nm+cfg.e_total_nm)*(cfg.kd_t_nm+cfg.t_total_nm)),
                            window80_low_nm=lo,window80_high_nm=hi,high_dose_ept_nm=float(species[-1,5])))
        for p,z in zip(doses,species):
            row = {"alpha":alpha,"P_total_M":p*1e-9,"P_total_nM":p}
            row.update(dict(zip(("P_free_nM","E_free_nM","T_free_nM","EP_nM","PT_nM","EPT_nM"),z)))
            rows.append(row)
        LOG.info("alpha=%g | peak EPT=%.6f nM | optimal total P=%.6f nM | 80%% window=%s to %s nM",alpha,-opt.fun,10**opt.x,lo,hi)
    write_csv(out/"data_task2"/"equilibrium_species.csv", rows)
    write_csv(out/"data_task2"/"equilibrium_metrics.csv",metrics)
    return doses,data,metrics


def linker_ensembles(cfg, out):
    # Atom maps specify attachment-point proxies, NOT real E3/POI warheads.
    # Similar contour lengths do not imply a matched medicinal-chemistry pair.
    designs = {
        "Flexible PEG": "[CH3:1]COCCOCCOC[CH3:2]",
        "Rigid alkynyl": "[CH3:1]C#CC#CC#C[CH3:2]",
    }
    arrays, summaries, allrows = {}, [], []
    for name,smiles in designs.items():
        mol = Chem.AddHs(Chem.MolFromSmiles(smiles))
        anchors = [next(a.GetIdx() for a in mol.GetAtoms() if a.GetAtomMapNum()==m) for m in (1,2)]
        heavy = [a.GetIdx() for a in mol.GetAtoms() if a.GetAtomicNum()>1]
        linker_atoms = [a for a in heavy if a not in anchors]
        params = AllChem.ETKDGv3()
        params.randomSeed = cfg.seed
        params.numThreads = 1
        params.pruneRmsThresh = -1.0  # Exactly 100 draws; duplicates retained and disclosed.
        ids = list(AllChem.EmbedMultipleConfs(mol,numConfs=cfg.conformers,params=params))
        if len(ids) != cfg.conformers:
            raise RuntimeError(f"{name}: expected {cfg.conformers} conformers, embedded {len(ids)}")
        if not AllChem.MMFFHasAllMoleculeParams(mol):
            raise RuntimeError(f"MMFF94s parameters unavailable for {name}")
        results = AllChem.MMFFOptimizeMoleculeConfs(mol,numThreads=1,maxIters=3000,mmffVariant="MMFF94s")
        coords, rg, distances, energies = [], [], [], []
        stem = name.lower().replace(" ","_")
        writer = Chem.SDWriter(str(out/"data_task2"/(stem+"_conformers.sdf")))
        try:
            for cid,(status,energy) in zip(ids,results):
                if status != 0:
                    status = AllChem.MMFFOptimizeMolecule(mol,maxIters=10000,mmffVariant="MMFF94s",confId=cid)
                    props = AllChem.MMFFGetMoleculeProperties(mol,mmffVariant="MMFF94s")
                    energy = AllChem.MMFFGetMoleculeForceField(mol,props,confId=cid).CalcEnergy()
                if status != 0:
                    raise RuntimeError(f"{name} conformer {cid}: MMFF did not converge")
                xyz = np.array(mol.GetConformer(cid).GetPositions())
                dist = float(np.linalg.norm(xyz[anchors[0]]-xyz[anchors[1]]))
                # RDKit mass-weighted Rg includes explicit hydrogens.
                radius = float(rdMolDescriptors.CalcRadiusOfGyration(mol,confId=cid))
                coords.append(xyz[heavy]-xyz[heavy].mean(axis=0))
                rg.append(radius); distances.append(dist); energies.append(float(energy))
                mol.SetProp("_Name",f"{name} synthetic attachment-point proxy {cid}")
                for key,value in {"anchor_atom_maps":"1,2","distance_A":dist,"Rg_A":radius,"energy_kcal_mol":energy,"ensemble":"ETKDGv3 unweighted sampling; not a thermodynamic population"}.items():
                    mol.SetProp(key,str(value))
                writer.write(mol,confId=cid)
                allrows.append(dict(linker=name,conformer_id=cid,distance_A=dist,Rg_A=radius,energy_kcal_mol=energy,mmff_status=status))
        finally:
            writer.close()
        xyzs = np.asarray(coords)
        ref = xyzs[0]
        # Iterative generalized Procrustes alignment removes translation/rotation.
        for _ in range(30):
            aligned = []
            for xyz in xyzs:
                u,_,vt = np.linalg.svd(xyz.T@ref)
                rot = u@np.diag([1.,1.,np.linalg.det(u@vt)])@vt
                aligned.append(xyz@rot)
            aligned = np.array(aligned)
            mean = aligned.mean(axis=0)
            if np.max(np.abs(ref-mean)) < 1e-8:
                break
            ref = mean
        per_atom = np.sqrt(np.mean(np.sum((aligned-mean)**2,axis=2),axis=0))
        loc = [heavy.index(idx) for idx in linker_atoms]
        rmsf = float(np.sqrt(np.mean(per_atom[loc]**2)))
        ds,rs = np.array(distances),np.array(rg)
        fraction = float(np.mean((ds>=cfg.compatible_low_a)&(ds<=cfg.compatible_high_a)))
        summary = dict(linker=name,smiles=smiles,conformers=len(ids),mean_distance_A=float(ds.mean()),
                       distance_sd_A=float(ds.std(ddof=1)),linker_RMSF_A=rmsf,mean_Rg_A=float(rs.mean()),
                       compatible_fraction=fraction,mmff_converged=len(ids))
        summaries.append(summary)
        arrays[name] = dict(distances=ds,rg=rs,rmsf=per_atom)
        write_csv(out/"data_task2"/(stem+"_atom_rmsf.csv"),
                  [dict(atom_index=idx,is_anchor=idx in anchors,RMSF_A=float(v)) for idx,v in zip(heavy,per_atom)])
        LOG.info("%s | n=%d | r=%.4f +/- %.4f A | linker RMSF=%.4f A | Rg=%.4f A | illustrative compatibility=%.1f%%",
                 name,len(ids),ds.mean(),ds.std(ddof=1),rmsf,rs.mean(),100*fraction)
    write_csv(out/"data_task2"/"linker_conformers.csv",allrows)
    write_csv(out/"data_task2"/"linker_summary.csv",summaries)
    return arrays,summaries


def simulate(cfg,doses,alphas,rtol=2e-7,atol=1e-9,t_eval=None):
    doses,alphas = np.broadcast_arrays(np.asarray(doses,float),np.asarray(alphas,float))
    shape = doses.shape
    ds,aa = doses.ravel(),alphas.ravel()
    def rhs(_,log_fraction):
        target = cfg.t_total_nm*np.exp(log_fraction)
        c = Equilibrium.batch(ds,cfg.e_total_nm,target,cfg.kd_e_nm,cfg.kd_t_nm,aa)
        loss = cfg.vmax_nm_h*c/(cfg.km_nm+c)
        # Constant synthesis restores the untreated baseline if turnover > 0.
        return (cfg.basal_turnover_h*(cfg.t_total_nm-target)-loss)/target
    sol = solve_ivp(rhs,(0.,cfg.hours),np.zeros(ds.size),method="DOP853",rtol=rtol,atol=atol,t_eval=t_eval)
    if not sol.success or not np.all(np.isfinite(sol.y)):
        raise ArithmeticError("Degradation integration failed: "+sol.message)
    fractions = np.exp(sol.y).reshape(shape+(sol.t.size,))
    if np.min(fractions)<0 or np.max(fractions)>1+1e-8:
        raise ArithmeticError("Target fraction outside physical range")
    return sol.t,fractions


def degradation_profiles(cfg,doses,out):
    times = np.linspace(0,cfg.hours,97)
    times,fractions = simulate(cfg,doses[None,:],np.array(ALPHAS)[:,None],t_eval=times)
    metrics=[]
    for k,alpha in enumerate(ALPHAS):
        def fn(logp):
            _,ys=simulate(cfg,[10**logp],[alpha])
            return float(100*(1-ys[0,-1]))
        opt=minimize_scalar(lambda x:-fn(x),bounds=(-3,6),method="bounded",options={"xatol":2e-5})
        if not opt.success:
            raise ArithmeticError("Degradation peak optimization failed")
        low,high=threshold_window(fn,opt.x,-opt.fun,.5)
        metrics.append(dict(alpha=alpha,Dmax_pct=float(-opt.fun),DC50_low_nM=low,DC50_high_nM=high,
                            optimal_degradation_dose_nM=float(10**opt.x),time_h=cfg.hours))
        LOG.info("Synthetic assay alpha=%g | Dmax=%.5f%% | ascending DC50=%s nM | hook-side crossing=%s nM",alpha,-opt.fun,low,high)
    write_csv(out/"data_task2"/"degradation_metrics.csv",metrics)
    write_csv(out/"data_task2"/"degradation_timecourses.csv",
              (dict(alpha=alpha,P_total_nM=p,time_h=t,target_fraction=float(fractions[a,i,j]),degradation_pct=float(100*(1-fractions[a,i,j])))
               for a,alpha in enumerate(ALPHAS) for i,p in enumerate(doses) for j,t in enumerate(times)))
    # Readout models: HiBiT linear in remaining target plus explicit background.
    # Noise is added to readout only; mechanistic endpoints remain noise free.
    idx=2
    rng=np.random.default_rng(cfg.seed)
    endpoint=fractions[idx,:,-1]
    raw_mean=500+100000*endpoint
    raw=rng.normal(raw_mean[:,None],(0.03*raw_mean+100)[:,None],size=(len(doses),3))
    observed=100*(1-(raw-500)/100000)
    sem=observed.std(axis=1,ddof=1)/math.sqrt(3)
    mask=doses<=metrics[idx]["optimal_degradation_dose_nM"]
    dmax=metrics[idx]["Dmax_pct"]
    # Conditional rising-limb Hill fit: plateau fixed to mechanistic Dmax.
    # A single monotone Hill curve is never fitted across the descending limb.
    def hill(x,params):
        logdc,h=params
        return dmax*expit(h*(np.log(x)-logdc))
    fitted=least_squares(lambda pars:(hill(doses[mask],pars)-observed[mask].mean(axis=1))/np.maximum(sem[mask],0.5),
                         [np.log(metrics[idx]["DC50_low_nM"] or doses[0]),1.],
                         bounds=([np.log(1e-6),.05],[np.log(1e9),8.]),max_nfev=3000)
    if not fitted.success:
        raise ArithmeticError("Ascending-limb Hill fit failed")
    fit=dict(alpha=10.,DC50_hill_nM=float(np.exp(fitted.x[0])),hill_slope=float(fitted.x[1]),
             Dmax_fixed_pct=dmax,fit_points=int(mask.sum()),
             rising_limb_RMSE_pct=float(np.sqrt(np.mean((hill(doses[mask],fitted.x)-observed[mask].mean(axis=1))**2))),
             note="Conditional empirical rising-limb fit; Dmax fixed to mechanistic maximum; no descending-limb extrapolation")
    dump_json(out/"data_task2"/"hibit_hill_fit.json",fit)
    write_csv(out/"data_task2"/"synthetic_hibit_replicates.csv",
              (dict(P_total_nM=p,replicate=r+1,raw_RLU=float(raw[i,r]),background_RLU=500,
                    untreated_signal_RLU=100000,degradation_pct=float(observed[i,r]),is_rising_limb=bool(mask[i]))
               for i,p in enumerate(doses) for r in range(3)))
    LOG.info("HiBiT ascending Hill fit | DC50=%.5f nM | h=%.4f | RMSE=%.4f percentage points",fit["DC50_hill_nM"],fit["hill_slope"],fit["rising_limb_RMSE_pct"])
    return times,fractions,metrics,observed,sem,fit,mask


