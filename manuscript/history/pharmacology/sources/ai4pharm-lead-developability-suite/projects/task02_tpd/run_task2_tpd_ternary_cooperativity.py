def git_publish(out, generated):
    git_directory=out
    def git(*args,check=True):
        return subprocess.run(["git","-C",str(git_directory),*args],check=check,text=True,capture_output=True)
    top=git("rev-parse","--show-toplevel",check=False)
    if top.returncode:
        raise RuntimeError("Git publication unavailable: output is not inside an existing repository")
    repo=Path(top.stdout.strip()).resolve()
    # Generated pathspecs below are relative to the repository, including when
    # this project or the chosen output is nested several directories deep.
    git_directory=repo
    upstream=git("rev-parse","--abbrev-ref","--symbolic-full-name","@{u}",check=False)
    if upstream.returncode:
        raise RuntimeError("Git publication unavailable: no configured upstream; no remote was invented")
    staged=git("diff","--cached","--name-only").stdout.strip()
    if staged:
        raise RuntimeError("Existing staged changes detected; refusing to include unrelated work")
    relative=[p.resolve().relative_to(repo).as_posix() for p in generated]
    git("add","--",*relative)
    diff=git("diff","--cached","--quiet",check=False)
    if diff.returncode==1:
        git("commit","-m",COMMIT_MESSAGE)
    elif diff.returncode!=0:
        raise RuntimeError("Unable to inspect staged Task 2 diff")
    pushed=git("push",check=False)
    if pushed.returncode:
        raise RuntimeError("Git push failed: "+pushed.stderr.strip())
    print("Git commit/push completed.")


