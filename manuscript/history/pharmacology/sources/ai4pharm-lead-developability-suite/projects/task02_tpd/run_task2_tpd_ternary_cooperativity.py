def validate_numerics(cfg,engine,em,out):
    rng=np.random.default_rng(cfg.seed)
    errors=[]; batch_errors=[]; thermo_errors=[]
    for _ in range(120):
        p,e,t,ke,kt=10**rng.uniform([-3,-1,-1,-1,-1],[6,3,3,3,3])
